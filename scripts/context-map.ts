#!/usr/bin/env bun
/*
 * context-map [--check]: per-package agent context maps. Every `packages/<pkg>/context/` (or
 * `packages/<group>/<pkg>/context/`) holds reference files with frontmatter (`tags`, `sources`,
 * `verified`), one H1 and a summary paragraph. This writes each root's `INDEX.md` from them, the way
 * `.rulesync/scripts/emit-maps.mjs` writes the global reference index. `--check` writes nothing and
 * exits 1 listing every problem: a stale index, a missing field, a cited source path that does not
 * exist, a broken link inside the context, or a package file citing a context file that does not exist.
 * `scripts/context-map.test.ts` runs the check over this repo, so `test:scripts` enforces it.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, normalize, relative, resolve, sep } from "node:path"

export interface ContextRoot {
	/** Repo-relative, posix: `packages/base-ui/context`. */
	dir: string
	/** Repo-relative, posix: `packages/base-ui`. */
	packageDir: string
	/** Display name: the package folder's name. */
	name: string
}

export interface ContextFile {
	/** Relative to the context root, posix. */
	rel: string
	title: string
	summary: string
	tags: string[] | undefined
	sources: string[] | undefined
	verified: string | undefined
	/** Relative `.md` link targets in the body, anchors stripped. */
	links: string[]
}

export const BANNER = "<!-- Generated by scripts/context-map.ts. Do not hand-edit. -->"
const SEGMENTS = [
	"architecture",
	"solid",
	"react",
	"testing",
	"perf",
	"tooling",
	"workflows",
	"components",
	"decisions",
]
const EMPTY_SOURCES_ALLOWED = new Set(["glossary.md", "decisions/log.md"])
const SUMMARY_MAX = 120
const SKIP_DIRS = new Set(["node_modules", "dist", "build", "coverage", "test-results", "playwright-report", "types"])
const SCANNED = /\.(?:[cm]?[jt]sx?|mdx?|ya?ml)$/
const CITATION = /(?:^|[^\w.-])context\/((?:[\w-]+\/)*[\w.-]+\.md)\b/g

const posix = (path: string) => path.split(sep).join("/")

function isDir(path: string): boolean {
	return existsSync(path) && statSync(path).isDirectory()
}

export function discoverContextRoots(repoRoot: string): ContextRoot[] {
	const roots: ContextRoot[] = []
	const packages = join(repoRoot, "packages")
	if (!isDir(packages)) return roots
	const visit = (packageDir: string, depth: number) => {
		if (existsSync(join(packageDir, "package.json")) && isDir(join(packageDir, "context"))) {
			const rel = posix(relative(repoRoot, packageDir))
			roots.push({ dir: `${rel}/context`, packageDir: rel, name: rel.split("/").at(-1)! })
		}
		if (depth === 0) return
		for (const entry of readdirSync(packageDir, { withFileTypes: true })) {
			if (!entry.isDirectory() || entry.name.startsWith(".") || SKIP_DIRS.has(entry.name)) continue
			if (entry.name === "context" || entry.name === "src") continue
			visit(join(packageDir, entry.name), depth - 1)
		}
	}
	for (const entry of readdirSync(packages, { withFileTypes: true })) {
		if (entry.isDirectory() && !entry.name.startsWith(".")) visit(join(packages, entry.name), 1)
	}
	return roots.sort((a, b) => a.dir.localeCompare(b.dir))
}

function unquote(raw: string): string {
	const value = raw.trim()
	if (value.length >= 2 && (value[0] === '"' || value[0] === "'") && value.at(-1) === value[0]) {
		return value.slice(1, -1)
	}
	return value
}

function parseFrontmatter(text: string): { fields: Map<string, string>; body: string } {
	const fields = new Map<string, string>()
	const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text)
	if (!match) return { fields, body: text }
	for (const line of match[1]!.split(/\r?\n/)) {
		const field = /^([\w.-]+):\s*(.*)$/.exec(line)
		if (field) fields.set(field[1]!, field[2]!.trim())
	}
	return { fields, body: text.slice(match[0].length) }
}

function list(raw: string | undefined): string[] | undefined {
	if (raw === undefined || raw === "") return undefined
	if (!raw.startsWith("[") || !raw.endsWith("]")) return [unquote(raw)]
	return raw
		.slice(1, -1)
		.split(",")
		.map(unquote)
		.filter((item) => item !== "")
}

// Collapses ASCII whitespace only: a non-breaking space ("Base UI") is content the vale brand-name
// rule requires. A cut that would split a code span drops the open span, so no stray backtick leaks.
function oneLine(text: string): string {
	const flat = text.replace(/[ \t\r\n]+/g, " ").trim()
	if (flat.length <= SUMMARY_MAX) return flat
	let cut = flat.slice(0, SUMMARY_MAX - 1)
	if ((cut.match(/`/g) ?? []).length % 2 === 1) cut = cut.slice(0, cut.lastIndexOf("`"))
	return `${cut.trimEnd()}…`
}

function titleAndSummary(body: string): { title: string; summary: string } {
	const lines = body.split(/\r?\n/)
	const h1 = lines.findIndex((line) => /^#\s+\S/.test(line))
	if (h1 === -1) return { title: "", summary: "" }
	const title = lines[h1]!.replace(/^#\s+/, "").trim()
	const paragraph: string[] = []
	let fenced = false
	for (const line of lines.slice(h1 + 1)) {
		const trimmed = line.trim()
		if (trimmed.startsWith("```")) {
			fenced = !fenced
			if (paragraph.length > 0) break
			continue
		}
		if (fenced) continue
		if (trimmed === "") {
			if (paragraph.length > 0) break
			continue
		}
		if (/^(?:#|<!--|---|\||>)/.test(trimmed)) {
			if (paragraph.length > 0) break
			continue
		}
		paragraph.push(trimmed)
	}
	return { title, summary: paragraph.join(" ") }
}

function linksOf(body: string): string[] {
	const links: string[] = []
	for (const match of body.matchAll(/\]\(([^)\s]+)\)/g)) {
		const target = match[1]!.split("#")[0]!
		if (target === "" || /^[a-z][\w+.-]*:/i.test(target) || target.startsWith("/")) continue
		if (target.endsWith(".md")) links.push(target)
	}
	return links
}

export function parseContextFile(rel: string, text: string): ContextFile {
	const { fields, body } = parseFrontmatter(text)
	const { title, summary } = titleAndSummary(body)
	const sources = fields.has("sources") ? (list(fields.get("sources")) ?? []) : undefined
	return {
		rel,
		title,
		summary,
		tags: list(fields.get("tags")),
		sources,
		verified: fields.get("verified") ? unquote(fields.get("verified")!) : undefined,
		links: linksOf(body),
	}
}

function markdownFiles(dir: string, base = dir): string[] {
	const out: string[] = []
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		if (entry.name.startsWith(".")) continue
		const abs = join(dir, entry.name)
		if (entry.isDirectory()) out.push(...markdownFiles(abs, base))
		else if (entry.isFile() && entry.name.endsWith(".md")) out.push(posix(relative(base, abs)))
	}
	return out
}

/** Every context file of a root except its `INDEX.md`, sorted by path. */
export function readRoot(repoRoot: string, root: ContextRoot): ContextFile[] {
	const dir = join(repoRoot, root.dir)
	return markdownFiles(dir)
		.filter((rel) => rel !== "INDEX.md")
		.sort()
		.map((rel) => parseContextFile(rel, readFileSync(join(dir, rel), "utf8")))
}

const cell = (text: string) => oneLine(text).replace(/\|/g, "\\|")

function segmentOf(rel: string): string {
	return rel.includes("/") ? rel.split("/")[0]! : ""
}

function segmentRank(segment: string): number {
	if (segment === "") return -1
	const at = SEGMENTS.indexOf(segment)
	return at === -1 ? SEGMENTS.length : at
}

export function renderIndex(root: ContextRoot, files: readonly ContextFile[]): string {
	const groups = new Map<string, ContextFile[]>()
	for (const file of files) {
		const segment = segmentOf(file.rel)
		groups.set(segment, [...(groups.get(segment) ?? []), file])
	}
	const ordered = [...groups.keys()].sort((a, b) => segmentRank(a) - segmentRank(b) || a.localeCompare(b))
	const out = [
		BANNER,
		"",
		`# ${root.name} context`,
		"",
		"Agent context for this package, one topic per file. Read this map once; when a row matches the work, read that file in full.",
		"Each file lists the code it describes under `sources` and the date it was last checked under `verified`.",
		"After adding or editing a file, run `bun scripts/context-map.ts` from the repo root; `bun run test:scripts` fails on a stale map.",
	]
	for (const segment of ordered) {
		out.push(
			"",
			segment === "" ? "## overview" : `## ${segment}`,
			"",
			"| path | title | tags | summary |",
			"| --- | --- | --- | --- |",
		)
		for (const file of groups.get(segment)!) {
			out.push(
				`| ${cell(file.rel)} | ${cell(file.title)} | ${cell((file.tags ?? []).map((tag) => `\`${tag}\``).join(", "))} | ${cell(file.summary)} |`,
			)
		}
	}
	return `${out.join("\n")}\n`
}

function scannedFiles(dir: string): string[] {
	const out: string[] = []
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		if (entry.name.startsWith(".") || SKIP_DIRS.has(entry.name)) continue
		const abs = join(dir, entry.name)
		if (entry.isDirectory()) out.push(...scannedFiles(abs))
		else if (entry.isFile() && SCANNED.test(entry.name)) out.push(abs)
	}
	return out
}

function fileProblems(repoRoot: string, root: ContextRoot, file: ContextFile): string[] {
	const at = `${root.dir}/${file.rel}`
	const problems: string[] = []
	if (!file.title) problems.push(`${at}: missing H1`)
	if (!file.summary) problems.push(`${at}: missing summary`)
	if (!file.tags || file.tags.length === 0) problems.push(`${at}: missing tags`)
	if (file.sources === undefined) problems.push(`${at}: missing sources`)
	else if (file.sources.length === 0 && !EMPTY_SOURCES_ALLOWED.has(file.rel)) problems.push(`${at}: sources is empty`)
	for (const source of file.sources ?? []) {
		if (!existsSync(join(repoRoot, source))) problems.push(`${at}: source not found: ${source}`)
	}
	if (file.verified === undefined) problems.push(`${at}: missing verified`)
	else if (!/^\d{4}-\d{2}-\d{2}$/.test(file.verified)) problems.push(`${at}: verified is not YYYY-MM-DD`)
	const fileDir = dirname(join(repoRoot, root.dir, file.rel))
	for (const link of file.links) {
		if (!existsSync(resolve(fileDir, link))) problems.push(`${at}: broken link: ${link}`)
	}
	return problems
}

function citationProblems(repoRoot: string, root: ContextRoot): string[] {
	const problems: string[] = []
	const contextAbs = join(repoRoot, root.dir)
	for (const abs of scannedFiles(join(repoRoot, root.packageDir))) {
		const text = readFileSync(abs, "utf8")
		if (!text.includes("context/")) continue
		for (const match of text.matchAll(CITATION)) {
			const target = normalize(join(contextAbs, match[1]!))
			if (!target.startsWith(contextAbs) || !existsSync(target)) {
				problems.push(`${posix(relative(repoRoot, abs))}: cites missing context/${match[1]}`)
			}
		}
	}
	return problems
}

export function checkRoot(repoRoot: string, root: ContextRoot): string[] {
	const files = readRoot(repoRoot, root)
	const problems = files.flatMap((file) => fileProblems(repoRoot, root, file))
	const indexPath = join(repoRoot, root.dir, "INDEX.md")
	const current = existsSync(indexPath) ? readFileSync(indexPath, "utf8") : ""
	if (current !== renderIndex(root, files)) {
		problems.push(`${root.dir}/INDEX.md is missing or stale; run bun scripts/context-map.ts`)
	}
	problems.push(...citationProblems(repoRoot, root))
	return problems
}

if (import.meta.main) {
	const repoRoot = resolve(import.meta.dirname, "..")
	const check = process.argv.includes("--check")
	const roots = discoverContextRoots(repoRoot)
	if (check) {
		const problems = roots.flatMap((root) => checkRoot(repoRoot, root))
		for (const problem of problems) console.error(problem)
		console.log(`context-map: ${roots.length} root(s), ${problems.length} problem(s)`)
		process.exit(problems.length === 0 ? 0 : 1)
	}
	for (const root of roots) {
		writeFileSync(join(repoRoot, root.dir, "INDEX.md"), renderIndex(root, readRoot(repoRoot, root)))
		console.log(`context-map: wrote ${root.dir}/INDEX.md`)
	}
}
