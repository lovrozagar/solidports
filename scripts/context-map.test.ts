import { afterEach, describe, expect, test } from "bun:test"
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { checkRoot, discoverContextRoots, parseContextFile, readRoot, renderIndex } from "./context-map.ts"

const temps: string[] = []

afterEach(() => {
	for (const dir of temps.splice(0)) rmSync(dir, { recursive: true, force: true })
})

function repo(files: Record<string, string>): string {
	const root = mkdtempSync(join(tmpdir(), "context-map-"))
	temps.push(root)
	for (const [rel, body] of Object.entries(files)) {
		const abs = join(root, rel)
		mkdirSync(dirname(abs), { recursive: true })
		writeFileSync(abs, body)
	}
	return root
}

function doc(opts: { tags?: string; sources?: string; verified?: string; body?: string } = {}): string {
	const lines = ["---"]
	if (opts.tags !== undefined) lines.push(`tags: ${opts.tags}`)
	if (opts.sources !== undefined) lines.push(`sources: ${opts.sources}`)
	if (opts.verified !== undefined) lines.push(`verified: ${opts.verified}`)
	lines.push("---", "")
	return `${lines.join("\n")}${opts.body ?? "# Title\n\nSummary line.\n"}`
}

const valid = (body?: string) =>
	doc({ tags: "[a]", sources: "[packages/x/src/a.ts]", verified: "2026-10-16", ...(body ? { body } : {}) })

function generated(root: string): string {
	const [ctx] = discoverContextRoots(root)
	return renderIndex(ctx!, readRoot(root, ctx!))
}

function problems(files: Record<string, string>, withIndex = true): string[] {
	const root = repo({ "packages/x/package.json": "{}", "packages/x/src/a.ts": "", ...files })
	const [ctx] = discoverContextRoots(root)
	if (withIndex) writeFileSync(join(root, ctx!.dir, "INDEX.md"), renderIndex(ctx!, readRoot(root, ctx!)))
	return checkRoot(root, ctx!)
}

const empty = (body: string) => doc({ tags: "[a]", sources: "[]", verified: "2026-10-16", body })

function row(summary: string): string {
	const root = repo({
		"packages/x/package.json": "{}",
		"packages/x/src/a.ts": "",
		"packages/x/context/a.md": valid(`# A\n\n${summary}\n`),
	})
	return generated(root)
		.split("\n")
		.find((line) => line.startsWith("| a.md"))!
}

describe("parseContextFile", () => {
	test("reads frontmatter, the first H1 and the first paragraph after it", () => {
		const file = parseContextFile(
			"solid/reactivity.md",
			doc({
				tags: "[solid, effects]",
				sources: "[a.ts, b.ts]",
				verified: "2026-10-16",
				body: "# Reactivity\n\n```ts\ncode\n```\n\nEffects split into compute and apply.\nSecond line.\n\n## Next\n",
			}),
		)
		expect(file).toMatchObject({
			rel: "solid/reactivity.md",
			title: "Reactivity",
			summary: "Effects split into compute and apply. Second line.",
			tags: ["solid", "effects"],
			sources: ["a.ts", "b.ts"],
			verified: "2026-10-16",
		})
	})

	test("collects relative markdown links, not URLs or anchors", () => {
		const file = parseContextFile(
			"a/b.md",
			valid("# T\n\nS.\n\nSee [x](../c/d.md#part), [y](https://e.com/f.md), [z](#local) and [w](./g.md).\n"),
		)
		expect(file.links).toEqual(["../c/d.md", "./g.md"])
	})
})

describe("discoverContextRoots", () => {
	test("finds context folders of packages one and two levels under packages", () => {
		const root = repo({
			"packages/x/package.json": "{}",
			"packages/x/context/a.md": valid(),
			"packages/y/z/package.json": "{}",
			"packages/y/z/context/b.md": valid(),
			"packages/w/package.json": "{}",
			"packages/w/src/context/c.ts": "export {}",
			"packages/w/test/context/d.md": "# fixture",
			"packages/v/README.md": "# V",
		})
		expect(discoverContextRoots(root).map((ctx) => ctx.dir)).toEqual(["packages/x/context", "packages/y/z/context"])
	})
})

describe("renderIndex", () => {
	test("puts root files first, then segments in their fixed order, with escaped, truncated cells", () => {
		const root = repo({
			"packages/x/package.json": "{}",
			"packages/x/src/a.ts": "",
			"packages/x/context/components/button.md": valid("# Button\n\nA | pipe.\n"),
			"packages/x/context/architecture/layout.md": valid(`# Layout\n\n${"word ".repeat(40)}\n`),
			"packages/x/context/zzz/extra.md": valid("# Extra\n\nUnlisted segments sort last.\n"),
			"packages/x/context/glossary.md": valid("# Glossary\n\nTerms.\n"),
		})
		const index = generated(root)
		expect(index.startsWith("<!-- Generated by scripts/context-map.ts. Do not hand-edit. -->\n")).toBe(true)
		expect(index).toContain("# x context")
		const order = ["glossary.md", "## architecture", "## components", "## zzz"].map((s) => index.indexOf(s))
		expect(order).toEqual([...order].sort((a, b) => a - b))
		expect(order.every((at) => at > 0)).toBe(true)
		expect(index).toContain("| components/button.md | Button | `a` | A \\| pipe. |")
		const layoutRow = index.split("\n").find((line) => line.startsWith("| architecture/layout.md"))!
		const summary = layoutRow.split(" | ")[3]!.replace(/ \|$/, "")
		expect(summary.length).toBe(120)
		expect(summary.endsWith("…")).toBe(true)
	})
})

describe("summary cells", () => {
	test("keep non-breaking spaces, which the vale brand-name rule requires", () => {
		expect(row("Base\u00a0UI renders parts.")).toContain("Base\u00a0UI renders parts.")
	})

	test("never cut inside a code span when truncating", () => {
		const cell = row(`${"word ".repeat(20)}and \`eslint-plugin-solid\` with more words after it`)
			.split(" | ")[3]!
			.replace(/ \|$/, "")
		expect(cell.split("`").length % 2).toBe(1)
		expect(cell.endsWith("…")).toBe(true)
		expect(cell.length).toBeLessThanOrEqual(120)
	})
})

describe("checkRoot", () => {
	test("a valid root with a current index has no problems", () => {
		expect(problems({ "packages/x/context/a.md": valid() })).toEqual([])
	})

	test("reports missing frontmatter fields", () => {
		const out = problems({ "packages/x/context/a.md": doc({}) })
		expect(out).toEqual(
			expect.arrayContaining([
				expect.stringContaining("a.md: missing tags"),
				expect.stringContaining("a.md: missing sources"),
				expect.stringContaining("a.md: missing verified"),
			]),
		)
	})

	test("allows empty sources only for the glossary and the decision log", () => {
		expect(
			problems({
				"packages/x/context/glossary.md": empty("# G\n\nTerms.\n"),
				"packages/x/context/decisions/log.md": empty("# Log\n\nEntries.\n"),
			}),
		).toEqual([])
		expect(problems({ "packages/x/context/a.md": empty("# A\n\nS.\n") })).toEqual([
			expect.stringContaining("a.md: sources is empty"),
		])
	})

	test("reports a source path that does not exist", () => {
		const out = problems({
			"packages/x/context/a.md": doc({ tags: "[a]", sources: "[packages/x/src/gone.ts]", verified: "2026-10-16" }),
		})
		expect(out).toEqual([expect.stringContaining("a.md: source not found: packages/x/src/gone.ts")])
	})

	test("reports a malformed verified date", () => {
		const out = problems({
			"packages/x/context/a.md": doc({ tags: "[a]", sources: "[packages/x/src/a.ts]", verified: "yesterday" }),
		})
		expect(out).toEqual([expect.stringContaining("a.md: verified is not YYYY-MM-DD")])
	})

	test("reports a missing title or summary", () => {
		expect(problems({ "packages/x/context/a.md": valid("No heading here.\n") })).toEqual(
			expect.arrayContaining([
				expect.stringContaining("a.md: missing H1"),
				expect.stringContaining("a.md: missing summary"),
			]),
		)
	})

	test("reports a broken relative link inside context", () => {
		const out = problems({
			"packages/x/context/a/b.md": valid("# B\n\nSee [c](../c.md) and [d](../d.md).\n"),
			"packages/x/context/c.md": valid(),
		})
		expect(out).toEqual([expect.stringContaining("a/b.md: broken link: ../d.md")])
	})

	test("reports a stale or missing index", () => {
		expect(problems({ "packages/x/context/a.md": valid() }, false)).toEqual([
			expect.stringContaining("INDEX.md is missing or stale"),
		])
	})

	test("reports package files that cite a context file that does not exist", () => {
		const out = problems({
			"packages/x/context/a.md": valid(),
			"packages/x/src/b.ts": "// See packages/x/context/a.md and context/gone/file.md.\n",
		})
		expect(out).toEqual([expect.stringContaining("packages/x/src/b.ts: cites missing context/gone/file.md")])
	})
})

describe("this repo", () => {
	test("every context root is valid and its index is current", () => {
		const root = resolve(import.meta.dirname, "..")
		const out = discoverContextRoots(root).flatMap((ctx) => checkRoot(root, ctx))
		expect(out).toEqual([])
	})
})
